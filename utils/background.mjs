// Settings for the topographic background (components/TopoBackground.vue), read from
// config.toml [background] by scripts/build-background.mjs. Anything missing uses the default;
// anything wrong fails the build, like the other config sections.
export const BACKGROUND_DEFAULTS = {
  enabled: true,
  dataSaver: 'sparse',
  contours: 28,
  startContours: 8,
  featureSize: 260,
  indexEvery: 5,
  trails: 3,
  drawSeconds: 90
}

// config.toml key -> setting (true or false)
const BOOLEANS = {
  enabled: 'enabled'
}

// What to do when the browser asks to save data: draw a lighter pattern, skip it, or ignore the hint
export const DATA_SAVER_MODES = ['sparse', 'skip', 'full']

// config.toml key -> [setting, min, max] (whole numbers)
const NUMBERS = {
  contours: ['contours', 8, 60],
  start_contours: ['startContours', 1, 60],
  feature_size: ['featureSize', 80, 800],
  index_every: ['indexEvery', 0, 20],
  trails: ['trails', 0, 6],
  draw_seconds: ['drawSeconds', 0, 600]
}

export const buildBackgroundConfig = (toml = {}) => {
  const section = toml?.background ?? {}
  const config = { ...BACKGROUND_DEFAULTS }
  const problems = []
  if (typeof section !== 'object' || Array.isArray(section)) {
    return { config, problems: ['[background] must be a table of settings'] }
  }

  for (const [key, value] of Object.entries(section)) {
    if (Object.hasOwn(BOOLEANS, key)) {
      if (typeof value === 'boolean') config[BOOLEANS[key]] = value
      else problems.push(`[background] ${key} must be true or false`)
    } else if (key === 'data_saver') {
      if (DATA_SAVER_MODES.includes(value)) config.dataSaver = value
      else problems.push(`[background] data_saver must be one of ${DATA_SAVER_MODES.map(mode => `"${mode}"`).join(', ')}`)
    } else if (Object.hasOwn(NUMBERS, key)) {
      const [setting, min, max] = NUMBERS[key]
      if (Number.isInteger(value) && value >= min && value <= max) config[setting] = value
      else problems.push(`[background] ${key} must be a whole number from ${min} to ${max}`)
    } else {
      problems.push(`[background] ${JSON.stringify(key)} isn't a setting`)
    }
  }
  if (config.startContours > config.contours) {
    problems.push(`[background] start_contours (${config.startContours}) can't be more than contours (${config.contours})`)
    config.startContours = Math.min(BACKGROUND_DEFAULTS.startContours, config.contours)
  }
  return { config, problems }
}

// Whether the visitor's browser is asking to save data: Data Saver / Lite mode (saveData), the
// prefers-reduced-data media query, or a very slow connection. Pass what the browser reports.
const SLOW_CONNECTIONS = new Set(['slow-2g', '2g'])
export const wantsLessData = ({ saveData = false, reducedData = false, effectiveType = '' } = {}) =>
  saveData === true || reducedData === true || SLOW_CONNECTIONS.has(effectiveType)

// The pattern to build for this visitor, as options for buildTopo (utils/topo.mjs), or null for
// none. When the browser asks to save data and data_saver is "sparse", the pattern is lighter: half
// the contours (and half the starting ones), larger hills, no trails, and a coarser grid (fewer points to draw).
export const LIGHT_CELL_PX = 12
export const topoOptions = (config, lessData = false) => {
  if (!config.enabled) return null
  const full = {
    contours: config.contours,
    featureSize: config.featureSize,
    indexEvery: config.indexEvery,
    trails: config.trails,
    startContours: config.startContours
  }
  if (!lessData || config.dataSaver === 'full') return full
  if (config.dataSaver === 'skip') return null
  const contours = Math.max(8, Math.round(config.contours / 2))
  return {
    contours,
    featureSize: Math.min(800, Math.round(config.featureSize * 1.4)),
    indexEvery: config.indexEvery,
    trails: 0,
    startContours: Math.min(contours, Math.max(1, Math.round(config.startContours / 2))),
    cellSize: LIGHT_CELL_PX
  }
}

export const backgroundModule = config =>
  `// Generated by scripts/build-background.mjs from config.toml [background]. Don't edit.\nexport default ${JSON.stringify(config, null, 2)}\n`
