// Settings for the topographic background (components/TopoBackground.vue), read from
// config.toml [background] by scripts/build-background.mjs. Anything missing uses the default;
// anything wrong fails the build, like the other config sections.
export const BACKGROUND_DEFAULTS = {
  enabled: true,
  contours: 28,
  featureSize: 260,
  indexEvery: 5,
  trails: 3,
  drawSeconds: 90
}

// config.toml key -> [setting, min, max] (whole numbers)
const NUMBERS = {
  contours: ['contours', 8, 60],
  feature_size: ['featureSize', 80, 800],
  index_every: ['indexEvery', 0, 20],
  trails: ['trails', 0, 6],
  draw_seconds: ['drawSeconds', 0, 600]
}

export const buildBackgroundConfig = (toml = {}) => {
  const section = toml?.background ?? {}
  const config = { ...BACKGROUND_DEFAULTS }
  const problems = []
  if (typeof section !== 'object' || Array.isArray(section)) {
    return { config, problems: ['[background] must be a table of settings'] }
  }

  for (const [key, value] of Object.entries(section)) {
    if (key === 'enabled') {
      if (typeof value === 'boolean') config.enabled = value
      else problems.push('[background] enabled must be true or false')
    } else if (Object.hasOwn(NUMBERS, key)) {
      const [setting, min, max] = NUMBERS[key]
      if (Number.isInteger(value) && value >= min && value <= max) config[setting] = value
      else problems.push(`[background] ${key} must be a whole number from ${min} to ${max}`)
    } else {
      problems.push(`[background] ${JSON.stringify(key)} isn't a setting`)
    }
  }
  return { config, problems }
}

export const backgroundModule = config =>
  `// Generated by scripts/build-background.mjs from config.toml [background]. Don't edit.\nexport default ${JSON.stringify(config, null, 2)}\n`
