// SwiftUI-style springs for the web. SwiftUI describes a spring by a perceptual duration and a
// bounce (Spring(duration:bounce:)), solves a real damped spring from those, and starts it at the
// gesture's velocity, so a fling carries straight into the animation instead of jolting to a
// fixed curve. This does the same sums: the exact solution of a unit-mass spring, sampled into a
// CSS linear() easing that runs for as long as the spring takes to settle. Pure and deterministic.

// SwiftUI's presets (.smooth, .snappy, .bouncy), and its plain .spring (response 0.55, no bounce)
export const SPRINGS = {
  smooth: { duration: 0.5, bounce: 0 },
  snappy: { duration: 0.5, bounce: 0.15 },
  bouncy: { duration: 0.5, bounce: 0.3 },
  spring: { duration: 0.55, bounce: 0 }
}

// Spring(duration:bounce:) as a physical spring with mass 1: the stiffness sets the period and
// the bounce takes damping away (a negative bounce is overdamped, slower to arrive)
export const springPhysics = ({ duration = 0.5, bounce = 0 } = {}) => {
  const stiffness = (2 * Math.PI / duration) ** 2
  const damping = bounce >= 0 ? (4 * Math.PI * (1 - bounce)) / duration : (4 * Math.PI) / (duration * (1 + bounce))
  return { stiffness, damping, mass: 1 }
}

// Progress from 0 to 1 at t seconds, starting at `velocity` (in whole distances per second, the
// way SwiftUI takes a gesture's velocity). Returns [position, velocity].
export const springAt = (t, { stiffness, damping, mass = 1 }, velocity = 0) => {
  const w0 = Math.sqrt(stiffness / mass)
  const zeta = damping / (2 * Math.sqrt(stiffness * mass))
  // y is the distance still to go (starts at -1), so position = 1 + y
  if (zeta < 1) {
    const wd = w0 * Math.sqrt(1 - zeta * zeta)
    const a = -1
    const b = (velocity + zeta * w0 * a) / wd
    const decay = Math.exp(-zeta * w0 * t)
    const cos = Math.cos(wd * t)
    const sin = Math.sin(wd * t)
    const y = decay * (a * cos + b * sin)
    const dy = decay * ((b * wd - zeta * w0 * a) * cos - (a * wd + zeta * w0 * b) * sin)
    return [1 + y, dy]
  }
  if (Math.abs(zeta - 1) < 1e-9) {
    const a = -1
    const b = velocity + w0 * a
    const decay = Math.exp(-w0 * t)
    return [1 + decay * (a + b * t), decay * (b - w0 * (a + b * t))]
  }
  const root = w0 * Math.sqrt(zeta * zeta - 1)
  const r1 = -zeta * w0 + root
  const r2 = -zeta * w0 - root
  const c2 = (velocity + r1) / (r2 - r1)
  const c1 = -1 - c2
  const e1 = Math.exp(r1 * t)
  const e2 = Math.exp(r2 * t)
  return [1 + c1 * e1 + c2 * e2, c1 * r1 * e1 + c2 * r2 * e2]
}

// How long until the spring is at rest: within `epsilon` of the end and moving slower than that
// per tenth of a second, from then on (checked over the following half a second)
export const settleTime = (physics, velocity = 0, epsilon = 0.001) => {
  const step = 1 / 120
  const still = t => {
    const [x, v] = springAt(t, physics, velocity)
    return Math.abs(1 - x) < epsilon && Math.abs(v) * 0.1 < epsilon
  }
  for (let t = step; t < 10; t += step) {
    if (!still(t)) continue
    let rest = true
    for (let u = t + step; rest && u < t + 0.5; u += step) rest = still(u)
    if (rest) return t
  }
  return 10
}

const round = n => Number(n.toFixed(4))

// A spring as a CSS easing: { easing: 'linear(0, …, 1)', seconds } to use as
// `transition: transform <seconds>s <easing>`. `velocity` starts it moving (see springAt).
export const springEasing = ({ duration = 0.5, bounce = 0, velocity = 0 } = {}, points = 48) => {
  const physics = springPhysics({ duration, bounce })
  const seconds = settleTime(physics, velocity)
  const stops = [0]
  for (let i = 1; i < points; i++) stops.push(round(springAt((seconds * i) / points, physics, velocity)[0]))
  stops.push(1)
  return { easing: `linear(${stops.join(', ')})`, seconds: round(seconds) }
}

// The presets as CSS custom properties, with a plain curve for browsers without linear()
// (assets/css/springs.css, written by scripts/build-springs.mjs)
const FALLBACKS = {
  smooth: 'cubic-bezier(0.25, 0.1, 0.25, 1)',
  snappy: 'cubic-bezier(0.2, 0.9, 0.3, 1.05)',
  bouncy: 'cubic-bezier(0.2, 0.8, 0.3, 1.2)',
  spring: 'cubic-bezier(0.25, 0.1, 0.25, 1)'
}

export const springCss = () => {
  const names = Object.keys(SPRINGS)
  const curves = names.map(name => [name, springEasing(SPRINGS[name])])
  const lines = [
    '/* Generated by scripts/build-springs.mjs from utils/spring.mjs. Do not edit. */',
    '/* SwiftUI\'s spring presets: use as `transition: transform var(--spring-bouncy-duration) var(--spring-bouncy)` */',
    ':root {',
    ...curves.flatMap(([name, { easing, seconds }]) => [
      `  --spring-${name}: ${easing};`,
      `  --spring-${name}-duration: ${seconds}s;`
    ]),
    '}',
    '',
    '@supports not (transition-timing-function: linear(0, 1)) {',
    '  :root {',
    ...names.map(name => `    --spring-${name}: ${FALLBACKS[name]};`),
    '  }',
    '}',
    ''
  ]
  return lines.join('\n')
}
