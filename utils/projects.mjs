// Rules for the Projects page: which repos show, their status and tags, plus search and
// sort. Pure, so the build script, the page and the tests share one implementation.
// config.toml [projects]:
//   wip       work-in-progress repos (every other non-fork is "Active")
//   forks     forks to show (other forks stay hidden)
//   featured  repos tagged "featured" (shown first when sorting by featured)
//   hackathon repos tagged "hackathon"

export const REPO_NAME = /^[A-Za-z0-9._-]{1,100}$/
export const FILTERS = ['all', 'active', 'wip', 'fork']
export const TAG_LABELS = { featured: 'Featured', hackathon: 'Hackathon' }
const CONFIG_TAGS = ['featured', 'hackathon']
const SORTS = {
  updated: (a, b) => String(b.updated_at ?? '').localeCompare(String(a.updated_at ?? '')),
  stars: (a, b) => (b.stargazers_count ?? 0) - (a.stargazers_count ?? 0),
  name: (a, b) => String(a.name).localeCompare(String(b.name)),
  featured: (a, b) =>
    Number(b.tags.includes('featured')) - Number(a.tags.includes('featured')) || SORTS.updated(a, b)
}

export const tagLabel = tag => (Object.hasOwn(TAG_LABELS, tag) ? TAG_LABELS[tag] : `#${tag}`)

// Validates the config and returns lowercased name sets; any problem should fail the build
export const buildProjectConfig = (toml = {}) => {
  const projects = toml?.projects ?? {}
  const problems = []
  const names = key => {
    const value = projects[key] ?? []
    if (!Array.isArray(value)) {
      problems.push(`[projects] ${key} must be a list of repo names`)
      return []
    }
    const valid = []
    for (const name of value) {
      if (typeof name === 'string' && REPO_NAME.test(name)) valid.push(name.toLowerCase())
      else problems.push(`[projects] ${key}: ${JSON.stringify(name)} isn't a GitHub repo name`)
    }
    return valid
  }
  const wip = new Set(names('wip'))
  const forks = new Set(names('forks'))
  const featured = new Set(names('featured'))
  const hackathon = new Set(names('hackathon'))
  for (const name of wip) if (forks.has(name)) problems.push(`${name}: listed in both wip and forks`)
  return { wip, forks, featured, hackathon, problems }
}

// 'fork' | 'wip' | 'active', or null to hide the repo
export const categorize = (repo, config) => {
  const name = String(repo?.name ?? '').toLowerCase()
  if (repo?.fork === true) return config.forks.has(name) ? 'fork' : null
  return config.wip.has(name) ? 'wip' : 'active'
}

// Config tags first, then the repo's own GitHub topics. Only shown repos get tags.
export const tagsFor = (repo, config) => {
  const name = String(repo?.name ?? '').toLowerCase()
  const configTags = CONFIG_TAGS.filter(tag => config[tag].has(name))
  const topics = Array.isArray(repo?.topics) ? repo.topics.map(String) : []
  return [...new Set([...configTags, ...topics])]
}

// Plain text search over name, description, language and tags; no patterns
export const matchesQuery = (repo, query) => {
  const needle = String(query ?? '').trim().toLowerCase()
  if (!needle) return true
  const haystack = [repo.name, repo.description, repo.language, ...(Array.isArray(repo.tags) ? repo.tags : [])]
    .filter(Boolean)
    .join(' ')
    .toLowerCase()
  return haystack.includes(needle)
}

// Only keys we define can be used; anything else (including prototype names) sorts by update
export const sorter = key => (Object.hasOwn(SORTS, key) ? SORTS[key] : SORTS.updated)

// The list as shown: status filter, tag filter, search, then sort
export const visibleProjects = (list, { filter = 'all', tag = null, query = '', sort = 'updated' } = {}) =>
  list
    .filter(project => (filter === 'all' || project.category === filter) && (!tag || project.tags.includes(tag)))
    .filter(project => matchesQuery(project, query))
    .sort(sorter(sort))

// The generated data module the site imports at build time
export const projectsModule = ({ wip, forks, featured, hackathon }) =>
  `// Generated by scripts/build-projects.mjs from config.toml [projects]. Don't edit.\nexport default ${JSON.stringify(
    {
      projects: {
        wip: [...wip].sort(),
        forks: [...forks].sort(),
        featured: [...featured].sort(),
        hackathon: [...hackathon].sort()
      }
    },
    null,
    2
  )}\n`
