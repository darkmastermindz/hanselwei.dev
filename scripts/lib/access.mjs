// Pure allow-list logic for scripts/build-access.mjs (tested in tests/security/access-list.test.mjs)

// Plain addresses only: no quotes, backslashes, angle brackets, whitespace or control
// characters, which could never be a real sign-in email anyway
export const EMAIL = /^[a-z0-9.!#$%&*+/=?^_{|}~-]+@[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)+$/i
export const isEmail = value => typeof value === 'string' && value.length <= 254 && EMAIL.test(value)

// `codeowners` is the text of .github/CODEOWNERS, `config` the parsed config.toml.
// Returns { emails, owners, additional, problems }; any problem should fail the build.
export const buildAllowList = ({ codeowners = '', config = {} }) => {
  const access = config.access ?? {}
  const githubEmails = Object.fromEntries(
    Object.entries(access.github ?? {}).map(([user, email]) => [user.toLowerCase(), String(email).toLowerCase()])
  )

  // Owners named in CODEOWNERS: each line is "<pattern> <owner> <owner> ..."
  const owners = new Set()
  for (const line of codeowners.split('\n')) {
    line.replace(/#.*/, '').trim().split(/\s+/).slice(1).forEach(token => owners.add(token))
  }

  const emails = new Set()
  const problems = []
  for (const owner of owners) {
    if (isEmail(owner)) emails.add(owner.toLowerCase())
    else if (owner.startsWith('@') && owner.includes('/')) problems.push(`${owner}: teams aren't supported; list the people in [access] instead`)
    else if (owner.startsWith('@')) {
      const email = Object.hasOwn(githubEmails, owner.slice(1).toLowerCase()) ? githubEmails[owner.slice(1).toLowerCase()] : null
      if (isEmail(email)) emails.add(email)
      else if (email) problems.push(`${owner}: ${JSON.stringify(email)} under [access.github] isn't an email address`)
      else problems.push(`${owner}: add their email under [access.github] in config.toml`)
    } else problems.push(`${JSON.stringify(owner)}: not a GitHub user or email address (.github/CODEOWNERS)`)
  }
  const additional = Array.isArray(access.additional) ? access.additional : []
  if (access.additional !== undefined && !Array.isArray(access.additional)) problems.push('[access] additional must be a list of emails')
  for (const email of additional) {
    if (isEmail(email)) emails.add(email.toLowerCase())
    else problems.push(`${JSON.stringify(email)}: not an email address ([access] additional in config.toml)`)
  }

  return { emails: [...emails].sort(), owners: owners.size, additional: additional.length, problems }
}

// The generated netlify/lib/access.mjs module
export const accessModule = emails =>
  `// Generated by scripts/build-access.mjs from .github/CODEOWNERS and config.toml. Don't edit.\nexport default ${JSON.stringify({ emails }, null, 2)}\n`
