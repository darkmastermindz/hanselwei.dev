// Builds the sign-in allow-list from .github/CODEOWNERS plus [access] in config.toml,
// and writes it to netlify/lib/access.mjs (git-ignored) for the Identity functions.
// Runs before every build (pregenerate/prebuild) and fails it on a bad entry, so a
// code owner can't silently end up locked out.
import { readFile, writeFile } from 'node:fs/promises'
import { parse } from 'smol-toml'

const EMAIL = /^[^\s@]+@[^\s@]+\.[^\s@]+$/
const root = new URL('../', import.meta.url)
const read = async path => readFile(new URL(path, root), 'utf8').catch(() => '')

const config = parse((await read('config.toml')) || '')
const access = config.access ?? {}
const githubEmails = Object.fromEntries(
  Object.entries(access.github ?? {}).map(([user, email]) => [user.toLowerCase(), String(email).toLowerCase()])
)

// Owners named in CODEOWNERS: each line is "<pattern> <owner> <owner> ..."
const owners = new Set()
for (const line of (await read('.github/CODEOWNERS')).split('\n')) {
  const tokens = line.replace(/#.*/, '').trim().split(/\s+/).slice(1)
  tokens.forEach(token => owners.add(token))
}

const emails = new Set()
const problems = []
for (const owner of owners) {
  if (EMAIL.test(owner)) emails.add(owner.toLowerCase())
  else if (owner.startsWith('@') && owner.includes('/')) problems.push(`${owner}: teams aren't supported; list the people in [access] instead`)
  else if (owner.startsWith('@')) {
    const email = githubEmails[owner.slice(1).toLowerCase()]
    if (email) emails.add(email)
    else problems.push(`${owner}: add their email under [access.github] in config.toml`)
  }
}
for (const email of access.additional ?? []) {
  if (EMAIL.test(email)) emails.add(email.toLowerCase())
  else problems.push(`${email}: not an email address ([access] additional in config.toml)`)
}

if (problems.length) {
  console.error(`[build-access] Can't build the sign-in allow-list:\n  ${problems.join('\n  ')}`)
  process.exit(1)
}

const list = [...emails].sort()
await writeFile(
  new URL('netlify/lib/access.mjs', root),
  `// Generated by scripts/build-access.mjs from .github/CODEOWNERS and config.toml. Don't edit.\nexport default ${JSON.stringify({ emails: list }, null, 2)}\n`
)
console.log(`[build-access] ${list.length} account(s) can sign in, from ${owners.size} code owner(s) and ${(access.additional ?? []).length} additional`)
