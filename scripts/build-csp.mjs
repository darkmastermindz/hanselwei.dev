// Runs after `nuxt generate`: hashes the inline scripts in the generated pages and
// writes the Content-Security-Policy to .output/public/_headers (Netlify applies it
// alongside the [[headers]] in netlify.toml).
//
// Production enforces the policy. Deploy previews and branch deploys only report
// violations (Netlify's preview toolbar injects its own scripts). CSP_MODE=report-only
// or CSP_MODE=enforce overrides either.
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { parse } from 'smol-toml'
import { buildCsp, handlerHashes, inlineScriptHashes } from './lib/csp.mjs'
import { luckyConfig } from '../utils/lucky.mjs'

const OUT = new URL('../.output/public/', import.meta.url)

const htmlFiles = async dir =>
  (await readdir(dir, { recursive: true })).filter(name => name.endsWith('.html')).map(name => new URL(name, dir))

const scripts = new Set()
const handlers = new Set()
const files = await htmlFiles(OUT)
for (const file of files) {
  const html = await readFile(file, 'utf8')
  inlineScriptHashes(html).forEach(h => scripts.add(h))
  handlerHashes(html).forEach(h => handlers.add(h))
}

const mode = process.env.CSP_MODE || (!process.env.CONTEXT || process.env.CONTEXT === 'production' ? 'enforce' : 'report-only')
const header = mode === 'report-only' ? 'Content-Security-Policy-Report-Only' : 'Content-Security-Policy'
// Google's search, only with a search engine set for I'm Feeling Lucky (config.toml [lucky])
const toml = parse(await readFile(new URL('../config.toml', import.meta.url), 'utf8').catch(() => ''))
const googleSearch = Boolean(luckyConfig(toml).config.searchEngineId)
const policy = buildCsp({ scripts, handlers, reportOnly: mode === 'report-only', googleSearch })

// Keep any other _headers rules; replace this script's block if it already ran
const MARK = '# Generated by scripts/build-csp.mjs'
let existing = ''
try {
  existing = (await readFile(new URL('_headers', OUT), 'utf8')).split(MARK)[0].trimEnd()
} catch {}
await writeFile(new URL('_headers', OUT), `${existing ? `${existing}\n\n` : ''}${MARK}\n/*\n  ${header}: ${policy}\n`)
console.log(`[build-csp] ${header} for ${files.length} page(s): ${scripts.size} inline script(s), ${handlers.size} handler(s) allowed by hash`)
